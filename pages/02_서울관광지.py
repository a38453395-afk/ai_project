# -----------------------------
# 지도 생성
# -----------------------------
seoul_map = folium.Map(
    location=[37.5665, 126.9780],
    zoom_start=11
)

# 파란색 마커 추가
for name, info in places.items():
    folium.Marker(
        location=info["location"],
        popup=f"""
        <b>{info['emoji']} {name}</b>
        """,
        tooltip=name,
        icon=folium.Icon(
            color="blue",
            icon="info-sign"
        )
    ).add_to(seoul_map)

# -----------------------------
# 지도 크기 60%
# -----------------------------
col1, col2 = st.columns([3, 2])

with col1:
    st_folium(seoul_map, width=700, height=500)

# -----------------------------
# 관광지 선택
# -----------------------------
with col2:
    st.subheader("📍 관광지 상세 정보")

    selected_place = st.selectbox(
        "관광지를 선택하세요 👇",
        list(places.keys())
    )

    place = places[selected_place]

    st.markdown(f"## {place['emoji']} {selected_place}")

